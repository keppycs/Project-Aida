/** Package only named application assets. Never traverse web/local or copy credentials. */
import { lstat, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const marker = "// Generated by node scripts/build-admin-assets.mjs; safe to regenerate.\n";
async function safePath(name, directory = false) {
  const absolute = resolve(root, name);
  const parts = relative(root, absolute).split(sep);
  if (!parts.length || parts.some(part => !part || part === "..")) throw new Error("Asset outside the project.");
  let current = root;
  for (const part of parts) {
    current = join(current, part);
    const info = await lstat(current);
    if (info.isSymbolicLink()) throw new Error(`Linked asset is unavailable: ${name}`);
  }
  const info = await lstat(absolute);
  if (directory ? !info.isDirectory() : !info.isFile()) throw new Error(`Invalid asset: ${name}`);
  return absolute;
}
const files = new Map([
  ["/edit", "admin/live.html"],
  ["/edit/", "admin/live.html"],
  ["/edit/assets/admin.css", "admin/admin.css"],
  ["/edit/assets/editor.js", "admin/editor.js"],
  ["/edit/preview/watch.html", "web/watch.html"],
  ["/edit/assets/preview.css", "admin/preview.css"],
  ["/edit/preview/assets/favicons/flushed.svg", "web/assets/favicons/flushed.svg"],
  ["/edit/preview/assets/favicons/bug.png", "web/assets/favicons/bug.png"],
]);
for (const folder of ["web/css", "web/js", "web/js/player"]) {
  const directory = await safePath(folder, true);
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (!entry.isFile() || !/\.(?:css|js)$/.test(entry.name)) continue;
    files.set(`/edit/preview/${folder.slice(4)}/${entry.name}`, `${folder}/${entry.name}`);
  }
}
const types = { css: "text/css; charset=utf-8", js: "text/javascript; charset=utf-8", html: "text/html; charset=utf-8", svg: "image/svg+xml", png: "image/png" };
const assets = {};
for (const [url, name] of [...files].sort(([left], [right]) => left.localeCompare(right))) {
  const bytes = await readFile(await safePath(name));
  const extension = name.split(".").at(-1);
  assets[url] = { type: types[extension], body: extension === "png" ? bytes.toString("base64") : bytes.toString("utf8"), binary: extension === "png" };
}
// The private preview uses authenticated relative media even on the live hostname.
assets["/edit/preview/js/site-env.js"].body += "\nwindow.shouldUseLocalCmaf = () => true;\n";
const outputDirectory = join(root, "edge", "generated");
try { await lstat(outputDirectory); await safePath("edge/generated", true); }
catch (error) { if (error.code !== "ENOENT") throw error; await mkdir(outputDirectory); }
const output = join(outputDirectory, "admin-assets.mjs");
try {
  await safePath("edge/generated/admin-assets.mjs");
  if (!(await readFile(output, "utf8")).startsWith(marker)) throw new Error("Refusing to replace a non-generated asset bundle.");
} catch (error) { if (error.code !== "ENOENT") throw error; }
await writeFile(output, `${marker}export default ${JSON.stringify(assets)};\n`, "utf8");
console.log(`Packaged ${files.size} approved owner-editor assets.`);
