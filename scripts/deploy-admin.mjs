/** Fixed owner-Worker deployer. Dry run unless --apply; no global config or npm. */
import { createHash } from "node:crypto";
import { lstat, readFile, realpath } from "node:fs/promises";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const WORKER = "aida-owner-editor";
export const MODULES = Object.freeze(["admin-worker.mjs", "admin-auth.mjs", "admin-b2.mjs", "admin-library.mjs", "admin-assets.mjs", "generated/admin-assets.mjs"]);
const PLAIN = ["SITE_ORIGIN", "ACCESS_TEAM_DOMAIN", "ACCESS_AUD", "OWNER_EMAIL", "ACCESS_SERVICE_CLIENT_ID", "B2_BUCKET_ID"];
const SECRET = ["B2_KEY_ID", "B2_SECRET_KEY"];
const KEYS = ["CLOUDFLARE_ACCOUNT_ID", "CLOUDFLARE_API_TOKEN", ...PLAIN, ...SECRET, "LEGACY_VISIBILITY"];
const ASSET_MARKER = "// Generated by node scripts/build-admin-assets.mjs; safe to regenerate.\n";
const plain = value => value && typeof value === "object" && !Array.isArray(value);
export class DeployError extends Error {}

async function safeFile(root, name, limit) {
  const base = resolve(root), path = resolve(base, name), baseRelative = relative(ROOT, base);
  if (isAbsolute(baseRelative) || baseRelative === ".." || baseRelative.startsWith(`..${sep}`)) throw new DeployError("Deployment files must stay inside this project.");
  const parts = relative(base, path).split(sep);
  if (!parts.length || parts.some(part => !part || part === "..") || isAbsolute(relative(base, path))) throw new DeployError("Invalid deployment file path.");
  // Check every ancestor before resolving/opening a file; reject junctions too.
  let current = ROOT;
  for (const part of [...baseRelative.split(sep).filter(Boolean), ...parts]) {
    current = join(current, part);
    const info = await lstat(current);
    if (info.isSymbolicLink() || (info.fileAttributes & 0x400)) throw new DeployError("Linked deployment files are unavailable.");
    if (resolve(await realpath(current)).toLowerCase() !== resolve(current).toLowerCase()) throw new DeployError("Redirected deployment files are unavailable.");
  }
  const info = await lstat(path);
  if (!info.isFile() || info.size > limit) throw new DeployError("Deployment file is missing, not regular, or oversized.");
  return readFile(path);
}

export function validateConfig(values) {
  if (!plain(values) || Object.keys(values).some(key => !KEYS.includes(key))) throw new DeployError("Unknown deployment configuration field.");
  const config = {};
  for (const key of KEYS.filter(key => key !== "LEGACY_VISIBILITY")) {
    if (typeof values[key] !== "string" || !values[key].trim() || /[\r\n\0]/.test(values[key]) || values[key].length > 4096) throw new DeployError(`Missing or invalid ${key}.`);
    config[key] = values[key].trim();
  }
  if (!/^[a-f0-9]{32}$/i.test(config.CLOUDFLARE_ACCOUNT_ID) || !/^[a-f0-9]{24}$/i.test(config.B2_BUCKET_ID)) throw new DeployError("Invalid account or bucket identifier.");
  if (config.SITE_ORIGIN !== "https://keppy.dev") throw new DeployError("This helper deploys only the keppy.dev owner editor.");
  if (!/^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.cloudflareaccess\.com$/.test(config.ACCESS_TEAM_DOMAIN) ||
      !/^[a-f0-9]{64}$/i.test(config.ACCESS_AUD) || !/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(config.OWNER_EMAIL) ||
      !/^[A-Za-z0-9_-]+\.access$/.test(config.ACCESS_SERVICE_CLIENT_ID)) throw new DeployError("Invalid Access application configuration.");
  config.OWNER_EMAIL = config.OWNER_EMAIL.toLowerCase();
  let legacy = values.LEGACY_VISIBILITY ?? {};
  try { if (typeof legacy === "string") legacy = JSON.parse(legacy); } catch { throw new DeployError("Invalid legacy visibility mapping."); }
  if (!plain(legacy) || Object.entries(legacy).some(([id, visibility]) => !/^[A-Za-z0-9_-]{1,128}$/.test(id) || !["public", "unlisted"].includes(visibility))) throw new DeployError("Invalid legacy visibility mapping.");
  config.LEGACY_VISIBILITY = JSON.stringify(legacy);
  return config;
}

export async function loadConfig({ configPath, env = process.env, root = ROOT } = {}) {
  let values = {};
  if (configPath) {
    const path = resolve(root, configPath), name = relative(resolve(root), path);
    // This fixed ignored subtree avoids Git/global-config discovery entirely.
    if (!name.startsWith(`logs${sep}`) || !name.endsWith(".json") || !/^logs\/\r?$/m.test((await safeFile(root, ".gitignore", 128_000)).toString("utf8"))) throw new DeployError("Explicit JSON deployment config must be in the project's ignored logs/ folder.");
    try { values = JSON.parse((await safeFile(root, name, 128_000)).toString("utf8")); }
    catch (error) { if (error instanceof DeployError) throw error; throw new DeployError("Could not read the explicit deployment JSON config."); }
    if (!plain(values) || Object.keys(values).some(key => !KEYS.includes(key))) throw new DeployError("Unknown deployment configuration field.");
  }
  for (const key of KEYS) if (typeof env[key] === "string" && env[key].trim()) values[key] = env[key];
  return validateConfig(values);
}

export async function prepareDeployment({ config, root = ROOT, initial = false }) {
  config = validateConfig(config);
  const modules = [];
  for (const name of MODULES) {
    const bytes = await safeFile(root, `edge/${name}`, 12_000_000);
    if (name === "generated/admin-assets.mjs" && !bytes.toString("utf8").startsWith(ASSET_MARKER)) throw new DeployError("Build the approved generated assets before deployment.");
    modules.push({ name, bytes });
  }
  const bindings = [...PLAIN, "LEGACY_VISIBILITY"].map(name => ({ name, type: "plain_text", text: config[name] }));
  bindings.push(...SECRET.map(name => ({ name, type: "secret_text", text: config[name] })));
  bindings.push({ name: "LIBRARY", type: "durable_object_namespace", class_name: "AidaLibrary" });
  const metadata = { main_module: "admin-worker.mjs", compatibility_date: "2026-10-18", bindings,
    ...(initial ? { migrations: { new_tag: "owner-library-v1", steps: [{ new_sqlite_classes: ["AidaLibrary"] }] } } : {}) };
  const body = new FormData();
  body.set("metadata", new Blob([JSON.stringify(metadata)], { type: "application/json" }), "metadata.json");
  for (const module of modules) body.set(module.name, new Blob([module.bytes], { type: "application/javascript+module" }), module.name);
  const summary = { worker: WORKER, mode: "dry-run", initial: Boolean(initial), compatibilityDate: metadata.compatibility_date,
    modules: modules.map(({ name, bytes }) => ({ name, bytes: bytes.length, sha256: createHash("sha256").update(bytes).digest("hex") })),
    bindings: bindings.map(({ name, type }) => ({ name, type })), migration: initial ? "owner-library-v1 (SQLite AidaLibrary)" : "unchanged",
    workersDev: false, previewUrls: false };
  return { config, body, summary };
}

async function checkedCall(fetcher, url, options, label) {
  let response;
  try { response = await fetcher(url, { ...options, redirect: "error", signal: AbortSignal.timeout(45_000) }); }
  catch { throw new DeployError(`${label} could not be confirmed. No automatic retry was made.`); }
  let result;
  try {
    const reader = response.body?.getReader();
    if (!reader) throw new Error();
    const chunks = []; let total = 0;
    try { for (;;) { const { value, done } = await reader.read(); if (done) break; total += value.length; if (total > 1_000_000) throw new Error(); chunks.push(value); } }
    finally { await reader.cancel().catch(() => {}); }
    result = JSON.parse(Buffer.concat(chunks).toString("utf8"));
  } catch { throw new DeployError(`${label} returned an invalid response (HTTP${response.status}).`); }
  if (!response.ok || result?.success !== true) throw new DeployError(`${label} failed (HTTP${response.status}).`);
}

export async function deploy(prepared, { apply = false, fetcher = globalThis.fetch } = {}) {
  if (!apply) return prepared.summary;
  const { config, body } = prepared;
  const endpoint = `https://api.cloudflare.com/client/v4/accounts/${config.CLOUDFLARE_ACCOUNT_ID}/workers/scripts/${WORKER}`;
  const headers = { Authorization: `Bearer ${config.CLOUDFLARE_API_TOKEN}` };
  await checkedCall(fetcher, endpoint, { method: "PUT", headers, body }, "Worker upload");
  try {
    await checkedCall(fetcher, endpoint + "/subdomain", { method: "POST", headers: { ...headers, "Content-Type": "application/json" }, body: JSON.stringify({ enabled: false, previews_enabled: false }) }, "Alternate URL disabling");
  } catch { throw new DeployError("Worker uploaded, but disabling workers.dev/preview URLs was not confirmed. Check those settings before enabling routes."); }
  return { ...prepared.summary, mode: "applied" };
}

export async function main(args = process.argv.slice(2), { env = process.env, root = ROOT, fetcher = globalThis.fetch, output = console.log } = {}) {
  let configPath, apply = false, initial = false;
  for (let index = 0; index < args.length; index++) {
    if (args[index] === "--apply" && !apply) apply = true;
    else if (args[index] === "--initial" && !initial) initial = true;
    else if (args[index] === "--config" && !configPath && args[index + 1] && !args[index + 1].startsWith("--")) configPath = args[++index];
    else throw new DeployError("Usage: node scripts/deploy-admin.mjs [--config logs/FILE.json] [--initial] [--apply]");
  }
  const config = await loadConfig({ configPath, env, root });
  const prepared = await prepareDeployment({ config, root, initial });
  const summary = await deploy(prepared, { apply, fetcher });
  output(JSON.stringify(summary, null, 2));
  return summary;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(error => { console.error(error instanceof DeployError ? error.message : "Deployment preparation failed. No configuration values were printed."); process.exitCode = 1; });
}
