import assert from "node:assert/strict";
import { mkdir, mkdtemp, rm, symlink, writeFile } from "node:fs/promises";
import { join, resolve, sep } from "node:path";
import test from "node:test";
import { ROOT, MODULES, WORKER, DeployError, deploy, loadConfig, main, prepareDeployment, validateConfig } from "../scripts/deploy-admin.mjs";

const config = { CLOUDFLARE_ACCOUNT_ID: "a".repeat(32), CLOUDFLARE_API_TOKEN: "synthetic-api-token-secret", SITE_ORIGIN: "https://keppy.dev", ACCESS_TEAM_DOMAIN: "synthetic.cloudflareaccess.com", ACCESS_AUD: "b".repeat(64), OWNER_EMAIL: "owner@example.invalid", ACCESS_SERVICE_CLIENT_ID: "synthetic.access", B2_BUCKET_ID: "c".repeat(24), B2_KEY_ID: "synthetic-b2-id", B2_SECRET_KEY: "synthetic-b2-secret", LEGACY_VISIBILITY: { old: "unlisted" } };
const marker = "// Generated by node scripts/build-admin-assets.mjs; safe to regenerate.\n";
async function removeGenerated(path) {
  const absolute = resolve(path), base = resolve(ROOT, "logs", "deploy-admin-tests");
  assert.ok(absolute.startsWith(base + sep), "Fixture deletion must stay inside its generated project subtree");
  await rm(absolute, { recursive: true, force: true });
}
async function fixture(t) {
  const folder = join(ROOT, "logs", "deploy-admin-tests");
  await mkdir(folder, { recursive: true });
  const root = await mkdtemp(join(folder, "fixture-"));
  t.after(() => removeGenerated(root)); // Generated solely by this test.
  await mkdir(join(root, "edge", "generated"), { recursive: true });
  await mkdir(join(root, "logs"));
  await writeFile(join(root, ".gitignore"), "logs/\n");
  for (const name of MODULES) await writeFile(join(root, "edge", name), (name.startsWith("generated/") ? marker : "") + "export default {};\n");
  return root;
}
const ok = () => Response.json({ success: true, result: {} });

test("dry run builds only fixed modules and redacts all configuration values", async t => {
  const root = await fixture(t), lines = [];
  await main([], { env: { ...config, LEGACY_VISIBILITY: JSON.stringify(config.LEGACY_VISIBILITY) }, root, output: line => lines.push(line), fetcher: () => assert.fail("Dry run must not call Cloudflare") });
  const result = JSON.parse(lines[0]);
  assert.equal(result.worker, WORKER); assert.equal(result.mode, "dry-run");
  assert.deepEqual(result.modules.map(module => module.name), [...MODULES]);
  assert.equal(result.bindings.find(binding => binding.name === "B2_SECRET_KEY").type, "secret_text");
  for (const secret of [config.CLOUDFLARE_API_TOKEN, config.B2_KEY_ID, config.B2_SECRET_KEY, config.OWNER_EMAIL, config.CLOUDFLARE_ACCOUNT_ID]) assert.equal(lines[0].includes(secret), false);
});

test("multipart uses module MIME, secret bindings and initial-only SQLite migration", async t => {
  const root = await fixture(t);
  for (const initial of [false, true]) {
    const prepared = await prepareDeployment({ config, root, initial });
    assert.deepEqual([...prepared.body.keys()], ["metadata", ...MODULES]);
    const metadata = JSON.parse(await prepared.body.get("metadata").text());
    assert.equal(metadata.main_module, "admin-worker.mjs");
    assert.deepEqual(metadata.bindings.find(binding => binding.name === "LIBRARY"), { name: "LIBRARY", type: "durable_object_namespace", class_name: "AidaLibrary" });
    assert.deepEqual(metadata.bindings.find(binding => binding.name === "B2_KEY_ID"), { name: "B2_KEY_ID", type: "secret_text", text: config.B2_KEY_ID });
    if (initial) assert.deepEqual(metadata.migrations, { new_tag: "owner-library-v1", steps: [{ new_sqlite_classes: ["AidaLibrary"] }] });
    else assert.equal(Object.hasOwn(metadata, "migrations"), false);
    for (const name of MODULES) assert.equal(prepared.body.get(name).type, "application/javascript+module");
  }
});

test("apply performs only fixed script PUT then alternate URL disable POST", async t => {
  const root = await fixture(t), calls = [];
  const prepared = await prepareDeployment({ config, root, initial: true });
  const result = await deploy(prepared, { apply: true, fetcher: async (url, options) => { calls.push({ url, options }); return ok(); } });
  assert.equal(result.mode, "applied");
  assert.equal(calls.length, 2);
  const base = `https://api.cloudflare.com/client/v4/accounts/${config.CLOUDFLARE_ACCOUNT_ID}/workers/scripts/aida-owner-editor`;
  assert.equal(calls[0].url, base); assert.equal(calls[0].options.method, "PUT");
  assert.equal(calls[0].options.body, prepared.body);
  assert.equal(calls[1].url, base + "/subdomain"); assert.equal(calls[1].options.method, "POST");
  assert.deepEqual(JSON.parse(calls[1].options.body), { enabled: false, previews_enabled: false });
  assert.ok(calls.every(call => call.options.redirect === "error" && call.options.headers.Authorization === `Bearer ${config.CLOUDFLARE_API_TOKEN}`));
});

test("explicit ignored project JSON is optional and process env overrides it", async t => {
  const root = await fixture(t);
  await writeFile(join(root, "logs", "config.json"), JSON.stringify(config));
  const loaded = await loadConfig({ root, configPath: "logs/config.json", env: { OWNER_EMAIL: "override@example.invalid", B2_SECRET_KEY: "" } });
  assert.equal(loaded.OWNER_EMAIL, "override@example.invalid"); assert.equal(loaded.B2_SECRET_KEY, config.B2_SECRET_KEY);
  await assert.rejects(loadConfig({ root, configPath: "../outside.json", env: {} }), DeployError);
  await assert.rejects(loadConfig({ root, configPath: "config.json", env: {} }), DeployError);
});

test("missing/unknown/unsafe configuration fails before network", async t => {
  const root = await fixture(t);
  for (const patch of [{ B2_SECRET_KEY: "" }, { CLOUDFLARE_ACCOUNT_ID: "../other" }, { SITE_ORIGIN: "https://other.invalid" }, { ACCESS_TEAM_DOMAIN: "https://bad.invalid" }, { OWNER_EMAIL: "no email" }, { LEGACY_VISIBILITY: { old: "private" } }, { EXTRA: "no" }]) {
    assert.throws(() => validateConfig({ ...config, ...patch }), DeployError);
  }
  await assert.rejects(main(["--apply"], { env: {}, root, fetcher: () => assert.fail("Missing configuration must not deploy") }), DeployError);
  await assert.rejects(main(["--worker", "different"], { env: config, root }), DeployError);
});

test("linked module parents and unmarked generated assets are rejected", async t => {
  const root = await fixture(t);
  await writeFile(join(root, "edge", "generated", "admin-assets.mjs"), "export default {};\n");
  await assert.rejects(prepareDeployment({ config, root }), /approved generated assets/);
  const linkedRoot = await fixture(t), target = await fixture(t);
  await removeGenerated(join(linkedRoot, "edge")); // Reproducible fixture modules only.
  await symlink(join(target, "edge"), join(linkedRoot, "edge"), process.platform === "win32" ? "junction" : "dir");
  await assert.rejects(prepareDeployment({ config, root: linkedRoot }), /Linked deployment/);
});

test("API failure is redacted and never retries or touches later endpoints", async t => {
  const root = await fixture(t), prepared = await prepareDeployment({ config, root });
  let calls = 0;
  await assert.rejects(deploy(prepared, { apply: true, fetcher: async () => { calls++; return Response.json({ success: false, errors: [{ message: config.B2_SECRET_KEY }] }, { status: 403 }); } }), error => error instanceof DeployError && !error.message.includes(config.B2_SECRET_KEY));
  assert.equal(calls, 1);
  calls = 0;
  await assert.rejects(deploy(prepared, { apply: true, fetcher: async () => { calls++; if (calls === 1) return ok(); throw new Error(config.CLOUDFLARE_API_TOKEN); } }), /Worker uploaded, but disabling/);
  assert.equal(calls, 2);
});
